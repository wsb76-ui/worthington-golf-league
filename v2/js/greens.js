export function haversineYards(lat1, lon1, lat2, lon2) {
  const R = 6371000;
  const toRad = x => x * Math.PI / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a = Math.sin(dLat / 2) ** 2
    + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  return Math.round(R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a)) * 1.09361);
}

// Front is the nearest of the front, left, and right edges. Same rule as the live app.
export function yardages(green, lat, lon) {
  if (!green || lat == null || lon == null) return null;
  const edges = [green.f, green.l, green.rt].filter(Boolean);
  return {
    front: Math.min(...edges.map(e => haversineYards(lat, lon, e[0], e[1]))),
    center: haversineYards(lat, lon, green.c[0], green.c[1]),
    back: haversineYards(lat, lon, green.r[0], green.r[1])
  };
}

export function playsLike(green, altMeters, centerYds) {
  if (!green || green.e == null || altMeters == null || centerYds == null) return null;
  const deltaFt = Math.round((green.e - altMeters * 3.28084) / 5) * 5;
  const adj = Math.round(deltaFt / 3);
  return { deltaFt, adj, plays: centerYds + adj };
}
